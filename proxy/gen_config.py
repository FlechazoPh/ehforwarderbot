#!/usr/bin/env python3
"""Build a mihomo (Clash.Meta) config from a VLESS subscription.

The resulting proxy/config.yaml contains node credentials and is git-ignored.

Usage:
    PROXY_SUB_URL=https://... python3 proxy/gen_config.py
    # or put PROXY_SUB_URL in .env

Optional env:
    PROXY_SUB_RESOLVE  "host:port:ip" passed to curl --resolve when the default
                       DNS answer for the subscription host is unreachable.
    PROXY_SERVER_IP    pin node server hostnames to this IP inside mihomo.
"""

import base64
import os
import pathlib
import subprocess
import sys
import urllib.parse

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent


def load_env() -> None:
    env = ROOT / ".env"
    if not env.exists():
        return
    for line in env.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


def fetch(url: str) -> str:
    cmd = ["curl", "-sS", "-m", "30", "-f"]
    if os.environ.get("PROXY_SUB_RESOLVE"):
        cmd += ["--resolve", os.environ["PROXY_SUB_RESOLVE"]]
    raw = subprocess.check_output(cmd + [url]).strip()
    try:
        text = raw.decode("utf-8")
        if "://" in text:
            return text
    except UnicodeDecodeError:
        pass
    return base64.b64decode(raw + b"=" * (-len(raw) % 4)).decode("utf-8")


def q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def vless_to_mihomo(link: str, used: set):
    u = urllib.parse.urlsplit(link)
    if u.scheme != "vless" or not u.hostname or not u.port:
        return None
    p = dict(urllib.parse.parse_qsl(u.query))
    name = urllib.parse.unquote(u.fragment) or f"{u.hostname}:{u.port}"
    base, i = name, 2
    while name in used:
        name, i = f"{base} #{i}", i + 1
    used.add(name)

    net = p.get("type", "tcp")
    tls = p.get("security") in ("tls", "reality")
    lines = [
        f"  - name: {q(name)}",
        "    type: vless",
        f"    server: {q(u.hostname)}",
        f"    port: {u.port}",
        f"    uuid: {q(urllib.parse.unquote(u.username or ''))}",
        "    udp: true",
        f"    tls: {'true' if tls else 'false'}",
        f"    network: {q(net)}",
    ]
    if p.get("flow"):
        lines.append(f"    flow: {q(p['flow'])}")
    sni = p.get("sni") or p.get("host")
    if tls and sni:
        lines.append(f"    servername: {q(sni)}")
    if p.get("fp"):
        lines.append(f"    client-fingerprint: {q(p['fp'])}")
    if p.get("alpn"):
        lines.append("    alpn: [" + ", ".join(q(a) for a in p["alpn"].split(",")) + "]")
    if p.get("security") == "reality":
        lines += [
            "    reality-opts:",
            f"      public-key: {q(p.get('pbk', ''))}",
            f"      short-id: {q(p.get('sid', ''))}",
        ]
    if net == "ws":
        lines += ["    ws-opts:", f"      path: {q(urllib.parse.unquote(p.get('path', '/')))}"]
        if p.get("host"):
            lines += ["      headers:", f"        Host: {q(p['host'])}"]
    elif net == "grpc":
        lines += ["    grpc-opts:", f"      grpc-service-name: {q(p.get('serviceName', ''))}"]
    return name, "\n".join(lines)


def main() -> int:
    load_env()
    url = os.environ.get("PROXY_SUB_URL")
    if not url:
        print("PROXY_SUB_URL is not set", file=sys.stderr)
        return 1
    used, names, blocks, servers = set(), [], [], set()
    for link in fetch(url).splitlines():
        r = vless_to_mihomo(link.strip(), used)
        if r:
            names.append(r[0])
            blocks.append(r[1])
            servers.add(urllib.parse.urlsplit(link.strip()).hostname)
    if not names:
        print("no usable vless node found", file=sys.stderr)
        return 1

    pin = os.environ.get("PROXY_SERVER_IP")
    hosts = "".join(f"  {q(h)}: {q(pin)}\n" for h in sorted(servers)) if pin else ""
    cfg = (
        "# generated by proxy/gen_config.py -- contains credentials, do not commit\n"
        "mixed-port: 7890\n"
        "allow-lan: true\n"
        "bind-address: '*'\n"
        "mode: rule\n"
        "log-level: warning\n"
        "ipv6: false\n"
        "unified-delay: true\n"
        "external-controller: 127.0.0.1:9090\n"
        + ("hosts:\n" + hosts if hosts else "")
        + "proxies:\n" + "\n".join(blocks) + "\n"
        "proxy-groups:\n"
        "  - name: TG\n"
        "    type: url-test\n"
        "    url: https://api.telegram.org/\n"
        "    expected-status: '200/302/404'\n"
        "    interval: 300\n"
        "    tolerance: 80\n"
        "    lazy: false\n"
        "    proxies:\n" + "".join(f"      - {q(n)}\n" for n in names)
        + "rules:\n"
        "  - MATCH,TG\n"
    )
    out = HERE / "config.yaml"
    out.write_text(cfg, encoding="utf-8")
    os.chmod(out, 0o600)
    print(f"wrote {out} with {len(names)} nodes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
